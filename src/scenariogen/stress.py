"""Scenario stress engine: full-reval P&L + ES-under-shock capital (S2).

Given a `MaterializedScenario`, computes the two first-class outputs the business asks for
(design §1, §8.4):

  P&L      full revaluation of the book under the shock (reuses the P2 `ScenarioEngine`).
  Capital  Expected Shortfall measured *around the shocked state* (the historical day
           moves are replayed on top of the scenario shock), compared to ES at today's
           state. ``capital_delta`` is the increase in required capital the scenario
           causes — e.g. "interest-rate impact on capital required".

ES-under-shock is the heavy measure (a full historical-VaR pass per scenario, n_days x
n_trades repricings), so it is opt-in via ``with_capital`` and uses the configured
lookback. The FRTB 97.5% ES level is the default capital measure.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from src.pricer.engine import PricingEngine
from src.pricer.input.common.trade import Trade
from src.pricer.input.common.valuation import ValuationContext
from src.pricer.risk.historical_var import FullRevalVarEngine, FullRevalVarResult
from src.pricer.risk.scenarios import ScenarioEngine, ScenarioPnl

from .factor_vector import MaterializedScenario
from .plausibility import PlausibilityChecker, PlausibilityResult

DEFAULT_CAPITAL_LEVEL = 0.975        # FRTB Expected Shortfall confidence


@dataclass
class ScenarioCapital:
    """ES at the shocked state vs today's state -> change in required capital."""

    level: float
    es_base: float
    es_shocked: float
    lookback_days: int

    @property
    def capital_delta(self) -> float:
        return self.es_shocked - self.es_base

    def as_dict(self) -> dict[str, Any]:
        return {"level": self.level, "es_base": self.es_base, "es_shocked": self.es_shocked,
                "capital_delta": self.capital_delta, "lookback_days": self.lookback_days}


@dataclass
class ScenarioStressResult:
    scenario: str
    severity: str
    valuation_date: str
    results: list[ScenarioPnl] = field(default_factory=list)
    capital: ScenarioCapital | None = None
    plausibility: PlausibilityResult | None = None
    materialized: dict[str, Any] = field(default_factory=dict)
    # Provenance of the scenario definition: "static" (authored config) or "llm" (generated by
    # src/scenariogen/llm). When "llm", ``llm`` carries the generation provenance (models, cost,
    # world_view_id, narrative, driver-leg origins) so the BFF/UI can surface it.
    source: str = "static"
    llm: dict[str, Any] | None = None
    # Dual-RAG value-add attribution: what MacroRAG (macro legs) and ARag (company legs)
    # each contributed vs the authored baseline (Δ + citations + fact-scaling), plus an
    # optional LLM narrative. Populated by the runner on a --dual-rag run.
    attribution: dict[str, Any] | None = None
    narrative: dict[str, Any] | None = None
    # P4 exit-value + funding post-processing (mode-(iii), additive; populated by the runner).
    # ``liquidity`` = F1 liquidity-horizon + bid-ask exit value; ``collateral`` = F2 cash line
    # (VM + IM). Both None when the passes are disabled, so the report stays byte-identical.
    liquidity: dict[str, Any] | None = None
    collateral: dict[str, Any] | None = None
    # F8 geopolitical calibration (P7): the GPR severity multiplier + live-trigger applied to a
    # geopolitically-tagged scenario (e.g. taiwan_geopolitical). None when untagged / feed absent.
    geopolitical: dict[str, Any] | None = None
    # F9 throughput calibration (P7): the AI-capex severity multiplier + thesis flag applied to a
    # throughput-tagged scenario (e.g. ai_bust). None when untagged / feed absent.
    throughput: dict[str, Any] | None = None
    # Severity anchoring (scenario-severity-anchor): the lead factor, its history anchors, the
    # enrichment's relative effect r, the rescale k and each factor's move vs its own anchors.
    # None for an unanchored scenario.
    anchoring: dict[str, Any] | None = None

    @property
    def scenario_version(self) -> str:
        return str(self.materialized.get("provenance", {}).get("scenario_version", ""))

    @property
    def total_pnl(self) -> float:
        return sum(r.pnl for r in self.results)

    def by_asset_class(self) -> dict[str, float]:
        agg: dict[str, float] = {}
        for r in self.results:
            agg[r.asset_class] = agg.get(r.asset_class, 0.0) + r.pnl
        return agg

    def to_dict(self) -> dict[str, Any]:
        return {
            "scenario": self.scenario,
            "severity": self.severity,
            "scenario_version": self.scenario_version,
            "valuation_date": self.valuation_date,
            "total_pnl": self.total_pnl,
            "pnl_by_asset_class": self.by_asset_class(),
            "trades": [r.as_dict() for r in self.results],
            "capital": self.capital.as_dict() if self.capital else None,
            "plausibility": self.plausibility.to_dict() if self.plausibility else None,
            "materialized": self.materialized,
            "source": self.source,
            "llm": self.llm,
            "attribution": self.attribution,
            "narrative": self.narrative,
            "liquidity": self.liquidity,
            "collateral": self.collateral,
            "geopolitical": self.geopolitical,
            "throughput": self.throughput,
            "anchoring": self.anchoring,
        }


class ScenarioStressEngine:
    def __init__(self, engine: PricingEngine, var_engine: FullRevalVarEngine):
        self.scen_engine = ScenarioEngine(engine)
        self.var_engine = var_engine

    def run(self, scenario: MaterializedScenario, trades: list[Trade], ctx: ValuationContext,
            *, with_capital: bool = True, capital_level: float = DEFAULT_CAPITAL_LEVEL,
            var_lookback: int | None = None,
            checker: PlausibilityChecker | None = None,
            base_result: FullRevalVarResult | None = None) -> ScenarioStressResult:
        result = ScenarioStressResult(
            scenario=scenario.name, severity=scenario.severity,
            valuation_date=ctx.valuation_date.isoformat(),
            results=self.scen_engine.run(scenario, trades, ctx),
            materialized=scenario.to_dict())

        if checker is not None:
            result.plausibility = checker.check(scenario)
        if with_capital:
            result.capital = self._capital(scenario, trades, ctx, capital_level, var_lookback,
                                           base_result=base_result)
        return result

    def _capital(self, scenario: MaterializedScenario, trades: list[Trade],
                 ctx: ValuationContext, level: float,
                 lookback: int | None,
                 base_result: FullRevalVarResult | None = None) -> ScenarioCapital:
        # The unshocked base ES is scenario-independent, so it is computed once per run and
        # passed in (``base_result``); only the shocked ES is scenario-specific.
        key = f"{level}"
        base = base_result if base_result is not None else self.var_engine.historical_var(
            trades, ctx, lookback=lookback)
        shocked = self.var_engine.historical_var(
            trades, ctx, lookback=lookback, base_transforms=scenario.transforms())
        return ScenarioCapital(
            level=level,
            es_base=float(base.es.get(key, 0.0)),
            es_shocked=float(shocked.es.get(key, 0.0)),
            lookback_days=base.lookback_days)
