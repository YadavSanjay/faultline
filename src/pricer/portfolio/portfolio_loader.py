"""Load portfolio.json into domain Trade objects, with flexible filtering.

`load_portfolio` supports the three invocation modes:
  * full book           -> load_portfolio()
  * a single asset class -> load_portfolio(asset_class="rates")
  * a single trade       -> load_portfolio(trade_id="TRADE_22")
"""

from __future__ import annotations

import json
import os
from datetime import date
from pathlib import Path

from ..input.bonds.instruments import CorporateBondTrade, TreasuryBondTrade
from ..input.cash_equity.instruments import CashEquityTrade
from ..input.common.enums import (
    AssetClass,
    CdsKind,
    DayCount,
    ExerciseStyle,
    Frequency,
    FxDirection,
    OptionRight,
    ProtectionSide,
    SettlementType,
    SwapDirection,
    TradeType,
)
from ..input.common.trade import Trade
from ..input.credit.instruments import CreditDefaultSwapTrade
from ..input.equity.instruments import EquityOptionTrade, OptionLeg
from ..input.fx.instruments import CrossCurrencySwapTrade, FxForwardTrade
from ..input.rates.instruments import (
    BermudanSwaptionTrade,
    CapTrade,
    EuropeanSwaptionTrade,
    OvernightIndexedSwapTrade,
)

_BOOK_DIR = Path(__file__).resolve().parent
_DEFAULT_PORTFOLIO = _BOOK_DIR / "portfolio.json"

# Risk-appetite book variants. The book is priced as a *variable*: `portfolio.json` is the
# active default (a copy of the configured default profile — aggressive), and each risk-appetite
# variant lives beside it as `portfolio_<book>.json`. Select with `--book`, the `PRICER_BOOK`
# env var, or the `book=` argument. Variants are generated by the sizing runner
# (`src/pricer/sizing/book_variants.py`) from the canonical base book (`portfolio_base.json`).
_KNOWN_BOOKS = ("base", "balanced", "core", "aggressive", "risky")


def resolve_book_path(book: str | None = None) -> Path:
    """Resolve a book name to its portfolio file.

    None / "default" / unset `PRICER_BOOK` → the active default `portfolio.json` (so plain
    `load_portfolio()` keeps pricing the default book). "base"/"original" → `portfolio_base.json`;
    any other name → `portfolio_<book>.json`.
    """
    book = (book or os.environ.get("PRICER_BOOK") or "").strip().lower()
    if not book or book == "default":
        return _DEFAULT_PORTFOLIO
    name = "base" if book in ("base", "original") else book
    p = _BOOK_DIR / f"portfolio_{name}.json"
    if not p.exists():
        raise FileNotFoundError(
            f"Portfolio book {book!r} not found ({p.name}). Known variants: {', '.join(_KNOWN_BOOKS)} "
            f"— (re)generate with `python -m src.pricer.sizing.sizing_runner`."
        )
    return p


def _build_rates_trade(d: dict) -> Trade:
    p = d.get("params", {})
    common = {
        "trade_id": d["trade_id"], "description": d["description"],
        "currency": d["currency"], "notional": d["notional"],
    }
    tt = TradeType(d["trade_type"])

    if tt == TradeType.OIS_SWAP:
        return OvernightIndexedSwapTrade(
            **common,
            direction=SwapDirection(p["direction"]),
            swap_tenor=p["swap_tenor"],
            fixed_rate=p["fixed_rate"],
            forward_start=p.get("forward_start", "0D"),
        )
    if tt == TradeType.EUROPEAN_SWAPTION:
        return EuropeanSwaptionTrade(
            **common,
            direction=SwapDirection(p["direction"]),
            option_tenor=p["option_tenor"],
            swap_tenor=p["swap_tenor"],
            strike=p.get("strike"),
            settlement=SettlementType(p.get("settlement", "physical")),
        )
    if tt == TradeType.BERMUDAN_SWAPTION:
        return BermudanSwaptionTrade(
            **common,
            direction=SwapDirection(p["direction"]),
            option_tenor=p["option_tenor"],
            swap_tenor=p["swap_tenor"],
            exercise_frequency=Frequency(p.get("exercise_frequency", "Annual")),
            strike=p.get("strike"),
            settlement=SettlementType(p.get("settlement", "physical")),
        )
    if tt == TradeType.CAP:
        return CapTrade(
            **common,
            cap_tenor=p["cap_tenor"],
            strike=p.get("strike"),
            caplet_frequency=Frequency(p.get("caplet_frequency", "Quarterly")),
        )
    raise NotImplementedError(f"Unsupported rates trade_type {tt!r} ({d['trade_id']})")


def _build_bonds_trade(d: dict) -> Trade:
    p = d.get("params", {})
    common = {
        "trade_id": d["trade_id"], "description": d["description"],
        "currency": d["currency"], "notional": d["notional"],
    }
    bond_terms = {
        "coupon": p["coupon"],
        "issue_date": date.fromisoformat(p["issue_date"]),
        "maturity_date": date.fromisoformat(p["maturity_date"]),
        "coupon_frequency": Frequency(p.get("coupon_frequency", "Semiannual")),
        "day_count": DayCount(p["day_count"]),
        "cusip": p.get("cusip"),
    }
    tt = TradeType(d["trade_type"])
    if tt == TradeType.CORP_BOND:
        return CorporateBondTrade(**common, issuer=p["issuer"], **bond_terms)
    if tt == TradeType.UST_BOND:
        return TreasuryBondTrade(**common, term=p.get("term", ""), **bond_terms)
    raise NotImplementedError(f"Unsupported bond trade_type {tt!r} ({d['trade_id']})")


def _build_options_trade(d: dict) -> Trade:
    p = d.get("params", {})
    legs = [
        OptionLeg(
            right=OptionRight(leg["right"]),
            strike=leg["strike"],
            expiry_date=date.fromisoformat(leg["expiry"]),
            exercise_style=ExerciseStyle(leg["exercise"]),
            quantity=leg.get("quantity", 1.0),
        )
        for leg in p["legs"]
    ]
    return EquityOptionTrade(
        trade_id=d["trade_id"], description=d["description"],
        currency=d["currency"], notional=d["notional"],
        underlier=p["underlier"], legs=legs,
        contract_multiplier=p.get("contract_multiplier", 100.0),
        structure=p.get("structure", "vanilla"),
    )


def _build_equity_trade(d: dict) -> Trade:
    p = d.get("params", {})
    return CashEquityTrade(
        trade_id=d["trade_id"], description=d["description"],
        currency=d["currency"], notional=d["notional"],
        ticker=p["ticker"], quantity=p["quantity"],
    )


def _build_credit_trade(d: dict) -> Trade:
    p = d.get("params", {})
    return CreditDefaultSwapTrade(
        trade_id=d["trade_id"], description=d["description"],
        currency=d["currency"], notional=d["notional"],
        reference=p["reference"], protection=ProtectionSide(p["protection"]),
        kind=CdsKind(p.get("kind", "single_name")), tenor=p.get("tenor", "5Y"),
        running_coupon=p.get("running_coupon", 0.01), recovery=p.get("recovery", 0.40),
    )


def _build_fx_trade(d: dict) -> Trade:
    p = d.get("params", {})
    common = {"trade_id": d["trade_id"], "description": d["description"],
              "currency": d["currency"], "notional": d["notional"]}
    tt = TradeType(d["trade_type"])
    if tt == TradeType.FX_FORWARD:
        return FxForwardTrade(
            **common, foreign_ccy=p["foreign_ccy"], usd_notional=p["usd_notional"],
            strike=p["strike"], maturity_date=date.fromisoformat(p["maturity_date"]),
            direction=FxDirection(p.get("direction", "long_usd")),
        )
    if tt == TradeType.XCCY_SWAP:
        return CrossCurrencySwapTrade(
            **common, foreign_ccy=p["foreign_ccy"], usd_notional=p["usd_notional"],
            contract_fx=p["contract_fx"], usd_fixed_rate=p["usd_fixed_rate"],
            foreign_fixed_rate=p["foreign_fixed_rate"],
            start_date=date.fromisoformat(p["start_date"]),
            maturity_date=date.fromisoformat(p["maturity_date"]),
            direction=FxDirection(p.get("direction", "long_usd")),
            frequency_months=p.get("frequency_months", 12),
        )
    raise NotImplementedError(f"Unsupported FX trade_type {tt!r} ({d['trade_id']})")


_BUILDERS = {
    AssetClass.RATES: _build_rates_trade,
    AssetClass.BONDS: _build_bonds_trade,
    AssetClass.OPTIONS: _build_options_trade,
    AssetClass.EQUITY: _build_equity_trade,
    AssetClass.CREDIT: _build_credit_trade,
    AssetClass.FX: _build_fx_trade,
}


def build_trade(d: dict) -> Trade:
    ac = AssetClass(d["asset_class"])
    if ac not in _BUILDERS:
        raise NotImplementedError(
            f"No trade builder for asset_class={ac.value!r} (trade {d['trade_id']}). "
            f"Supported: {sorted(a.value for a in _BUILDERS)}."
        )
    return _BUILDERS[ac](d)


class PortfolioConfig:
    def __init__(self, raw: dict, path: Path):
        self.raw = raw
        self.path = path

    @property
    def default_valuation_date(self) -> date:
        return date.fromisoformat(self.raw.get("default_valuation_date", date.today().isoformat()))

    @property
    def default_valuation_type(self) -> str:
        return str(self.raw.get("default_valuation_type", "PV"))


def load_portfolio_config(path: Path | None = None, book: str | None = None) -> PortfolioConfig:
    path = path or resolve_book_path(book)
    with open(path, encoding="utf-8") as fh:
        raw = json.load(fh)
    return PortfolioConfig(raw, path)


def build_portfolio(
    raw: dict,
    asset_class: str | None = None,
    trade_id: str | None = None,
) -> list[Trade]:
    """Build domain Trade objects from a raw portfolio dict, filtered.

    Works on any raw portfolio mapping — the live `portfolio.json` or a stored version
    replayed from the PortfolioStore (versioning) — which keeps version replay on the
    exact same construction path as a normal load.
    """
    out: list[Trade] = []
    for d in raw.get("trades", []):
        if asset_class and d["asset_class"] != asset_class:
            continue
        if trade_id and d["trade_id"] != trade_id:
            continue
        if AssetClass(d["asset_class"]) not in _BUILDERS:
            continue
        out.append(build_trade(d))
    return out


def load_portfolio(
    asset_class: str | None = None,
    trade_id: str | None = None,
    path: Path | None = None,
    book: str | None = None,
) -> list[Trade]:
    """Return domain Trade objects, filtered by asset class and/or trade id.

    ``book`` selects a risk-appetite variant (base/balanced/aggressive/risky); the default
    (None) is the active default book ``portfolio.json``. Only trades whose asset_class has a
    registered builder are constructed; others (not yet implemented) are skipped so the rest
    of the book still prices.
    """
    return build_portfolio(load_portfolio_config(path, book).raw, asset_class, trade_id)
